/**
 * GlassGroup: Glass on real DOM components (CSS and SVG backends).
 *
 * One group = one GlassSource (the DOM element whose content may be
 * refracted) + the surfaces drawn above it. The document chooses the
 * backend; the group reports what was requested, what runs, why, and what
 * the running backend does with each parameter.
 *
 *   const group = createGlassGroup({ source, material });
 *   const bar = group.attach(nav, { sizing: 'element', interaction: 'press' });
 *   group.setMaterial(next);   // cheap updates stay cheap (see `affects`)
 *   group.destroy();           // filters, layers, observers, listeners, loops
 *
 * WebGL2 does not read the DOM: a document that requests `webgl2` mounted
 * here runs on the automatic DOM path and says so in `status.reasons`.
 */

import { GlassContext, type ContextStatus } from '../core/context';
import { bindDrag, bindPress, type DragOptions } from '../core/interaction';
import { changedKeys, type GlassParams, type ParamKey, type ParamStage } from '../core/params';
import type { PathRequest, RenderPath, VerificationRecord } from '../core/renderer/capabilities';
import type { GlassSurface, Sizing } from '../core/surface';
import { glassParams, type GlassDocument } from '../model/document';
import { stagesFor } from '../model/glass';
import { resolveQuality, type QualityProfile } from '../model/quality';
import { supportReport, type Backend, type BackendRequest, type SupportLevel } from '../model/support';
import { RUNTIME_VERSION } from '../model/version';

export interface GlassGroupOptions {
  /** Opaque element whose content the SVG backend refracts. */
  source: HTMLElement;
  material: GlassDocument;
  /** Overrides `material.target.backend`. */
  backend?: BackendRequest;
  /** Use refraction only where a raster verification record matches the engine. */
  requireVerified?: boolean;
  verification?: readonly VerificationRecord[];
  /** Suspend while the source is off-screen or the page is hidden (default true). */
  autoSuspend?: boolean;
}

export interface AttachOptions {
  /** `element` (default): sized by layout. `params`: free surface sized by geometry.width/height. */
  sizing?: Sizing;
  radius?: number | 'capsule';
  /** `press`: press feedback on the host. `drag`: free dragging (params sizing). */
  interaction?: 'none' | 'press' | { drag: DragOptions };
}

export interface GroupStatus {
  requested: BackendRequest;
  /** Backend actually rendering. The opaque fallback is the CSS backend with `opaque: true`. */
  effective: Backend;
  opaque: boolean;
  path: RenderPath;
  reasons: string[];
  quality: QualityProfile;
  suspended: boolean;
  motionReduced: boolean;
  context: ContextStatus;
  support: { key: ParamKey; level: SupportLevel; note: string }[];
}

export interface UpdateReport {
  changed: ParamKey[];
  stages: ParamStage[];
  /** Displacement maps generated by this update (0 for every non-geometry change). */
  mapsGenerated: number;
}

const PATH_OF: Record<BackendRequest, PathRequest> = { auto: 'auto', svg: 'refraction', css: 'satin', webgl2: 'auto' };

/** Engine parameters with the quality profile applied (chroma off on Economy). */
export function engineParams(doc: GlassDocument): GlassParams {
  const p = glassParams(doc);
  return resolveQuality(doc.quality).chroma ? p : { ...p, chroma: 0 };
}

export class GlassGroup {
  readonly context: GlassContext;
  private doc: GlassDocument;
  private params: GlassParams;
  private requested: BackendRequest;
  private pathOverride: PathRequest | null = null;
  private readonly surfaces = new Map<GlassSurface, () => void>();
  private readonly listeners = new Set<(s: GroupStatus) => void>();
  private readonly cleanups: (() => void)[] = [];
  private offscreen = false;
  private hidden = false;
  private destroyed = false;

  constructor(options: GlassGroupOptions) {
    this.doc = options.material;
    this.params = engineParams(options.material);
    this.requested = options.backend ?? options.material.target.backend;
    const quality = resolveQuality(options.material.quality);
    this.context = new GlassContext({
      source: options.source,
      path: PATH_OF[this.requested],
      fallback: options.material.target.fallback === 'opaque' ? 'opaque' : 'satin',
      resolution: quality.mapResolution,
      mapCacheSize: quality.mapCache,
      runtimeVersion: RUNTIME_VERSION,
      ...(options.requireVerified !== undefined ? { requireVerified: options.requireVerified } : {}),
      ...(options.verification ? { verification: options.verification } : {}),
    });
    this.cleanups.push(this.context.onChange(() => this.emit()));
    if (options.autoSuspend ?? true) this.watchVisibility(options.source);
  }

  get material(): GlassDocument {
    return this.doc;
  }

  get status(): GroupStatus {
    const c = this.context.status;
    const effective: Backend = c.effective === 'refraction' ? 'svg' : 'css';
    const reasons = [...c.reasons];
    if (this.requested === 'webgl2' && !this.pathOverride) {
      reasons.unshift('WebGL2 non legge il DOM: sui componenti reali uso il percorso automatico');
    }
    return {
      requested: this.requested,
      effective,
      opaque: c.effective === 'opaque',
      path: c.effective,
      reasons,
      quality: resolveQuality(this.doc.quality),
      suspended: c.suspended,
      motionReduced: c.motionReduced,
      context: c,
      support: supportReport(effective),
    };
  }

  attach(host: HTMLElement, options: AttachOptions = {}): GlassSurface {
    const sizing = options.sizing ?? 'element';
    const surface = this.context.attach(host, {
      params: this.params,
      sizing,
      ...(options.radius !== undefined ? { radius: options.radius } : {}),
    });
    const i = options.interaction ?? 'none';
    const off = i === 'press' ? bindPress(surface) : typeof i === 'object' ? bindDrag(surface, i.drag) : () => {};
    this.surfaces.set(surface, off);
    return surface;
  }

  detach(surface: GlassSurface): void {
    const off = this.surfaces.get(surface);
    if (!off) return;
    off();
    this.surfaces.delete(surface);
    surface.destroy();
  }

  /** Applies a new document. Only geometry changes regenerate maps. */
  setMaterial(doc: GlassDocument): UpdateReport {
    const before = this.context.stats.mapRegenerations;
    const next = engineParams(doc);
    const changed = changedKeys(this.params, next);
    const prevQuality = resolveQuality(this.doc.quality);
    const quality = resolveQuality(doc.quality);
    const target = doc.target;
    this.doc = doc;
    this.params = next;
    if (quality.mapResolution !== prevQuality.mapResolution) this.context.setResolution(quality.mapResolution);
    this.context.setFallback(target.fallback === 'opaque' ? 'opaque' : 'satin');
    if (target.backend !== this.requested && !this.pathOverride) this.setBackend(target.backend);
    if (changed.length) for (const s of this.surfaces.keys()) s.setParams(next);
    this.emit();
    return { changed, stages: [...stagesFor(changed)], mapsGenerated: this.context.stats.mapRegenerations - before };
  }

  setBackend(request: BackendRequest): void {
    this.requested = request;
    this.pathOverride = null;
    this.context.setPath(PATH_OF[request]);
  }

  /** Low-level override of the DOM path, e.g. to inspect the opaque fallback. */
  setPathRequest(path: PathRequest | null): void {
    this.pathOverride = path;
    this.context.setPath(path ?? PATH_OF[this.requested]);
  }

  onStatus(listener: (s: GroupStatus) => void): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  /** Layout changed somewhere the observers cannot see: re-measure every surface. */
  invalidate(): void {
    this.context.measureAll();
  }

  suspend(): void {
    this.context.suspend();
  }

  resume(): void {
    if (this.offscreen || this.hidden) return;
    this.context.resume();
  }

  destroy(): void {
    if (this.destroyed) return;
    this.destroyed = true;
    for (const off of this.surfaces.values()) off();
    this.surfaces.clear();
    for (const c of this.cleanups.splice(0)) c();
    this.listeners.clear();
    this.context.destroy();
  }

  private emit() {
    if (this.destroyed || !this.listeners.size) return;
    const s = this.status;
    for (const l of this.listeners) l(s);
  }

  private watchVisibility(source: HTMLElement) {
    const doc = source.ownerDocument;
    const win = doc.defaultView;
    const sync = () => {
      if (this.offscreen || this.hidden) this.context.suspend();
      else this.context.resume();
    };
    const onVisibility = () => {
      this.hidden = doc.visibilityState === 'hidden';
      sync();
    };
    doc.addEventListener('visibilitychange', onVisibility);
    this.cleanups.push(() => doc.removeEventListener('visibilitychange', onVisibility));
    if (win && 'IntersectionObserver' in win) {
      const io = new win.IntersectionObserver((entries) => {
        const last = entries[entries.length - 1];
        if (!last) return;
        this.offscreen = !last.isIntersecting;
        sync();
      });
      io.observe(source);
      this.cleanups.push(() => io.disconnect());
    }
  }
}

export function createGlassGroup(options: GlassGroupOptions): GlassGroup {
  return new GlassGroup(options);
}
